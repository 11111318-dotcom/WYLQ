'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');

const html = fs.readFileSync(path.join(__dirname, '..', 'index.html'), 'utf8');
const inputStart = html.indexOf('<section id="view-input">');
const resultStart = html.indexOf('<section id="view-result" hidden>');
const targetSectionIndex = html.indexOf('id="targetSection"', resultStart);
const liuYuanSectionIndex = html.indexOf('id="liuYuanTargetSection"', resultStart);
const ninePalaceIndex = html.indexOf('id="ninePalaceSection"', resultStart);
const inputMarkup = html.slice(inputStart, resultStart);
const renderStart = html.indexOf('function renderLiuYuanTargetSection(target)');
const renderEnd = html.indexOf('function setFormError(message)', renderStart);
const renderFn = html.slice(renderStart, renderEnd);
const calculateRenderStart = html.indexOf('renderObservationPanel(target);renderSummary(birth,target);');
const calculateRenderEnd = html.indexOf('catch(renderErr)', calculateRenderStart);
const calculateRenderFlow = html.slice(calculateRenderStart, calculateRenderEnd);

assert.ok(inputStart >= 0 && resultStart > inputStart, 'input and result view boundaries must exist');
assert.ok(!inputMarkup.includes('liuYuan'), 'birth-entry view must not contain Liu-Yuan lookup controls');
assert.ok(!html.includes('liuYuanLookupSection'), 'standalone lookup card must be removed');
assert.ok(!html.includes('openLiuYuanDialogBtn'), 'manual launcher must be removed');
assert.ok(!html.includes('liuYuanDialog'), 'manual dialog must be removed');
assert.ok(!html.includes('liuYuanGanZhi'), 'manual Ganzhi selector must be removed');
assert.ok(targetSectionIndex >= 0 && liuYuanSectionIndex > targetSectionIndex, 'automatic results should follow the target-year summary');
assert.ok(ninePalaceIndex > liuYuanSectionIndex, 'automatic results should sit with target-year details');
assert.ok(renderStart >= 0 && renderFn.includes('computeLiuYuanZhengJiInfo(target.gz.gz)'), 'rendering must use the actual target snapshot Ganzhi');
assert.ok(renderFn.includes('target.year') && renderFn.includes('info.干支'), 'heading must show selected target year and resolved Ganzhi');
assert.ok(renderFn.includes('軌道1_六元正紀經文合論正化度') && renderFn.includes('軌道2_玄珠類經正對化分論生成數'), 'both reference tracks must remain visible');
assert.ok(calculateRenderFlow.includes('renderLiuYuanTargetSection(target)'), 'the result must render automatically during each calculation');
assert.ok(html.includes("const ids=['resultMeta','liuYuanTargetSection'"), 'rollback snapshot must include panel');
assert.ok(html.includes("['summary','liuYuanTargetSection','auditLog'"), 'clear list must include panel');
assert.equal((html.match(/id="liuYuanTargetSection"/g) || []).length, 1, 'exactly one automatic results panel must exist');
console.log('PASS: selected target year automatically drives 六元正紀 output; no separate Ganzhi selector or dialog remains.');
