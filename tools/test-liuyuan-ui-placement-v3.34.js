'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const html = fs.readFileSync(path.join(__dirname, '..', 'index.html'), 'utf8');
const inputStart = html.indexOf('<section id="view-input">');
const resultStart = html.indexOf('<section id="view-result" hidden>');
const targetSectionIndex = html.indexOf('id="targetSection"', resultStart);
const liuYuanSectionIndex = html.indexOf('id="liuYuanTargetSection"', resultStart);
const ninePalaceIndex = html.indexOf('id="ninePalaceSection"', resultStart);
const inputMarkup = html.slice(inputStart, resultStart);
const renderStart = html.indexOf('function renderLiuYuanTargetSection(target)');
const renderEnd = html.indexOf('function setFormError(message)', renderStart);
const renderFn = html.slice(renderStart, renderEnd);
const calculateRenderStart = html.indexOf('renderSummary(birth,target);condenseSummary(birth,target);');
const calculateRenderEnd = html.indexOf('catch(renderErr)', calculateRenderStart);
const calculateRenderFlow = html.slice(calculateRenderStart, calculateRenderEnd);
assert.ok(inputStart >= 0 && resultStart > inputStart, 'input and result view boundaries must exist');
assert.ok(!inputMarkup.includes('liuYuan'), 'birth-entry view must not contain Liu-Yuan controls');
assert.ok(!html.includes('liuYuanLookupSection') && !html.includes('openLiuYuanDialogBtn') && !html.includes('liuYuanDialog') && !html.includes('liuYuanGanZhi'), 'no obsolete manual Liu-Yuan controls');
assert.ok(targetSectionIndex >= 0 && liuYuanSectionIndex > targetSectionIndex, 'Liu-Yuan should follow target-year results');
assert.ok(ninePalaceIndex > liuYuanSectionIndex, 'Liu-Yuan should precede Nine-Palace details');
assert.ok(renderStart >= 0 && renderFn.includes('computeLiuYuanZhengJiInfo(target.gz.gz)'), 'renderer must use the actual target snapshot Ganzhi');
assert.ok(renderFn.includes('target.year') && renderFn.includes('info.干支'), 'heading must identify selected target year and Ganzhi');
assert.ok(renderFn.includes('軌道1_六元正紀經文合論正化度') && renderFn.includes('軌道2_玄珠類經正對化分論生成數'), 'both textual/numerical tracks must remain visible');
assert.ok(calculateRenderFlow.includes('renderLiuYuanTargetSection(target)'), 'rendering must occur automatically for each calculation');
assert.ok((html.match(/const ids=\['resultMeta','liuYuanTargetSection','precisionNotice'/g)||[]).length===2, 'reset and rollback snapshots must include the new panel');
assert.ok(html.includes("['summary','liuYuanTargetSection','auditLog'"), 'calculation clear list must include the panel');
assert.equal((html.match(/id="liuYuanTargetSection"/g)||[]).length, 1, 'exactly one panel must exist');
assert.ok(html.includes("sections:['sixSection','targetSection','liuYuanTargetSection','shengFuYuFaSection'"), 'panel must be in the annual result tab');
assert.ok(html.includes("liuYuanTargetSection:'六元正紀・正化／對化'"), 'section jump label must be present');
assert.ok(html.includes("APP_VERSION='3.32.0-security-yq14-integrated-liuyuan-v3.34.0'"), 'integrated version marker must be present');
console.log('PASS: integrated yq14 Liu-Yuan panel, target-year binding, annual navigation, reset and rollback wiring.');
