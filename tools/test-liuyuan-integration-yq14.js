'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const root = path.join(__dirname, '..');
const live = fs.readFileSync(path.join(root, 'index.html'), 'utf8');
const legacy = fs.readFileSync(path.join(root, 'versions', 'current-legacy.html'), 'utf8');
const dataStart = legacy.indexOf('/* 六元正紀查核模組');
const dataEnd = legacy.indexOf('const YUN_MAP', dataStart);
const liveDataStart = live.indexOf('/* 六元正紀查核模組');
const liveDataEnd = live.indexOf('const YUN_MAP', liveDataStart);
assert.ok(dataStart >= 0 && dataEnd > dataStart && liveDataStart >= 0 && liveDataEnd > liveDataStart, 'both legacy and integrated Liu-Yuan data blocks must exist');
let expected = legacy.slice(dataStart, dataEnd);
expected = expected.replace(/const FALLBACK_GAN = Object\.freeze\([\s\S]*?const FALLBACK_ZHI = Object\.freeze\([\s\S]*?\);\s*\n\s*let GAN_LIST, ZHI_LIST;\s*\ntry \{ GAN_LIST = Array\.isArray\(GAN\) \? GAN : FALLBACK_GAN; \} catch \(_\) \{ GAN_LIST = FALLBACK_GAN; \}\s*\ntry \{ ZHI_LIST = Array\.isArray\(ZHI\) \? ZHI : FALLBACK_ZHI; \} catch \(_\) \{ ZHI_LIST = FALLBACK_ZHI; \}\s*\n/, '');
expected = expected.replace(/\bGAN_LIST\b/g, 'GAN').replace(/\bZHI_LIST\b/g, 'ZHI');
assert.equal(live.slice(liveDataStart, liveDataEnd), expected, 'integrated data and pure calculation block must match archived module except shared GAN/ZHI binding');
const helperStart = legacy.indexOf('function liuyuanMakeElement');
const helperEnd = legacy.indexOf('function setFormError', helperStart);
const liveHelperStart = live.indexOf('function liuyuanMakeElement');
const liveHelperEnd = live.indexOf('function setFormError', liveHelperStart);
assert.ok(helperStart >= 0 && helperEnd > helperStart && liveHelperStart >= 0 && liveHelperEnd > liveHelperStart, 'render helpers must exist');
assert.equal(live.slice(liveHelperStart, liveHelperEnd), legacy.slice(helperStart, helperEnd), 'DOM renderer must be copied without edits');
assert.equal((live.slice(liveDataStart,liveDataEnd).match(/pairIndex:\s*\d+/g)||[]).length, 30, 'all 30 paired records must be retained');
const years = [...live.slice(liveDataStart,liveDataEnd).matchAll(/years: Object\.freeze\(\["([^"]+)",\s*"([^"]+)"\]\)/g)].flatMap(m=>[m[1],m[2]]);
assert.equal(years.length, 60, 'exactly 60 Ganzhi keys must be represented');
assert.equal(new Set(years).size, 60, 'all 60 Ganzhi keys must be unique');
assert.ok(live.includes('function computeLiuYuanZhengJiInfo(ganzhi)'), 'pure calculation entry point must be present');
assert.ok(live.includes('function renderLiuYuanTargetSection(target)'), 'result renderer must be present');
console.log('PASS: transplanted Liu-Yuan data/calculation/render code matches archived source; all 60 Ganzhi retained.');
